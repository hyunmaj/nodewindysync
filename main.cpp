#include <string>
#include <vector>

void sum_odds() {
    int acc = 0;
    for (int i = 1; i <= 10; ++i) {
        if (i % 2 != 0) acc += i;
    }
    (void)acc;
}

void least_multiple() {
    int a = 6, b = 8;
    int x = a, y = b;
    while (y != 0) {
        int t = x % y;
        x = y;
        y = t;
    }
    int lcm = a / x * b;
    (void)lcm;
}

void text_contains() {
    std::string text = "hidden harbor";
    std::string part = "harbor";
    bool found = false;
    for (std::size_t i = 0; i + part.size() <= text.size(); ++i) {
        bool match = true;
        for (std::size_t j = 0; j < part.size(); ++j) {
            if (text[i + j] != part[j]) { match = false; break; }
        }
        if (match) { found = true; break; }
    }
    (void)found;
}

void mod_cycle() {
    int acc = 0;
    for (int i = 0; i < 20; ++i) acc = (acc + i * 3) % 7;
    (void)acc;
}

extern "C" int brisk_boulder();
extern "C" void calm_bridge();
extern "C" void gentle_willow();
extern "C" void brisk_beacon();
extern "C" void radiant_harbor();

int main() {
    sum_odds();
    least_multiple();
    text_contains();
    mod_cycle();
    calm_bridge();
    gentle_willow();
    brisk_beacon();
    radiant_harbor();
    return brisk_boulder();
}
